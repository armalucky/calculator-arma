def build():
    tables = {}
    for page, charge, trajectory, start, end, step, pairs in PAGES:
        filename = f'{page} (2).jpg' if page <= 12 else f'{page}.jpg'
        source = 'references/m777-screenshots/'+filename
        assert (ROOT/source).is_file(), source
        key = f'm777-{charge}-{trajectory}'
        table = tables.setdefault(key, dict(id=key, weapon='m777', unitsPerCircle=6400,
            shell='M107 HE', rings=charge, trajectory=trajectory, source='', rows=[]))
        parsed = [pair.split('/') for pair in pairs.split()]
        assert len(parsed) == (end-start)//step+1, (page, len(parsed))
        for index, (elevation, seconds) in enumerate(parsed):
            row = dict(distance=start+index*step, elevation=int(elevation), seconds=float(seconds), source=source)
            prior = next((r for r in table['rows'] if r['distance']==row['distance']), None)
            if prior:
                assert (prior['elevation'],prior['seconds']) == (row['elevation'],row['seconds']), page
                prior['source'] += ' | '+source
            else:
                table['rows'].append(row)
        table['source'] += (' | ' if table['source'] else '')+filename
    for table in tables.values():
        rows = table['rows']
        step = 100 if table['rings']==1 else 200
        assert all(b['distance']-a['distance']==step for a,b in zip(rows,rows[1:])), table['id']
        assert all((b['elevation']>a['elevation']) == (table['trajectory']=='low') for a,b in zip(rows,rows[1:]))
    return list(tables.values())


if __name__ == '__main__':
    tables = build()
    (ROOT/'data/m777-tables.json').write_text(json.dumps(tables, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print(f'{len(tables)} tables, {sum(len(t["rows"]) for t in tables)} unique rows; 19 pages checked and merged')
